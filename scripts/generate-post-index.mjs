import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const postsRoot = join(root, 'src', 'content', 'posts');
const outputPath = join(root, 'src', 'lib', 'generated-posts.ts');
const contentRoot = '../content/posts/';

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) return walk(path);
    return entry.isFile() && entry.name.endsWith('.md') ? [path] : [];
  });
}

function normalizePath(path) {
  return path.split(sep).join('/');
}

function normalizeSlugPart(part) {
  return part.trim().replace(/\s+/g, '-');
}

function uniqueTags(tags) {
  return Array.from(new Set(tags.filter(Boolean)));
}

function parseFrontmatter(raw) {
  const match = raw.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!match) return { meta: new Map(), body: raw };

  const meta = new Map();
  match[1].split('\n').forEach((line) => {
    const index = line.indexOf(':');
    if (index === -1) return;
    meta.set(line.slice(0, index).trim(), line.slice(index + 1).trim());
  });

  return { meta, body: match[2].trim() };
}

function readTags(value = '') {
  return value
    .split(',')
    .map((tag) => tag.trim())
    .filter(Boolean);
}

function readBoolean(value = 'false') {
  return value.toLowerCase() === 'true';
}

function readTitleFromBody(body, fallback) {
  return body.match(/^#\s+(.+)$/m)?.[1]?.trim() || fallback;
}

function readSummaryFromBody(body) {
  return body
    .split('\n')
    .map((line) => line.trim())
    .find((line) =>
      line &&
      !line.startsWith('#') &&
      !line.startsWith('![') &&
      !line.startsWith('<!--') &&
      !line.startsWith('```')
    ) ?? '';
}

function toPost(path) {
  const sourcePath = `${contentRoot}${normalizePath(relative(postsRoot, path))}`;
  const raw = readFileSync(path, 'utf8');
  const parts = sourcePath.split('/');
  const filename = parts.pop() ?? '';
  const folder = parts.pop();
  const fileSlug = filename.replace(/\.md$/, '');
  const relativePath = sourcePath.startsWith(contentRoot)
    ? sourcePath.slice(contentRoot.length).replace(/\.md$/, '')
    : fileSlug;
  const relativeParts = relativePath.split('/');
  const [categoryDir] = relativeParts;
  const category = relativePath.includes('/') ? categoryDir : null;
  const slugParts = category && (fileSlug === 'index' || fileSlug === 'README' || fileSlug === '分享')
    ? relativeParts.slice(0, -1)
    : relativeParts;
  const pathSlug = category ? slugParts.map(normalizeSlugPart).join('-') : undefined;
  const { meta, body } = parseFrontmatter(raw);

  return {
    slug: pathSlug ?? (fileSlug === 'index' || fileSlug === 'README' || fileSlug === '分享'
      ? folder ?? fileSlug
      : fileSlug),
    sourcePath,
    category,
    title: meta.get('title') ?? readTitleFromBody(body, fileSlug),
    date: meta.get('date') ?? '2026-01-01',
    summary: meta.get('summary') ?? readSummaryFromBody(body),
    tags: uniqueTags([category, ...readTags(meta.get('tags'))]),
    cover: meta.get('cover'),
    readingTime: meta.get('readingTime') ?? '5 分钟',
    featured: readBoolean(meta.get('featured')),
  };
}

const posts = walk(postsRoot)
  .map(toPost)
  .sort((a, b) => b.date.localeCompare(a.date));

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(
  outputPath,
  `// Auto-generated by scripts/generate-post-index.mjs. Do not edit by hand.\n\nexport const generatedPosts = ${JSON.stringify(posts, null, 2)};\n`,
);
